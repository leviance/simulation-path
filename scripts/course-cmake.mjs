import { workbookOption } from "../lib/voxel-workbook.ts";

export function courseCmake(project, { hasSnapshotShaders = false } = {}) {
  const projectNumber = Number(project.id);
  const workOption = workbookOption(project.id);
  // An existing starter edit and a separately seeded work/ are distinct learner paths.
  const workbook = `
option(${workOption} "Build the learner's editable copy and test its own headers" OFF)
option(COURSE_TEST_STARTER "Test the learner's edits directly in starter/" OFF)
if(${workOption} AND COURSE_TEST_STARTER)
    message(FATAL_ERROR "Choose one learner tree: work/ or starter/, not both.")
endif()
if(${workOption})
    if(NOT EXISTS "\${CMAKE_CURRENT_SOURCE_DIR}/work")
        file(COPY "\${CMAKE_CURRENT_SOURCE_DIR}/starter/" DESTINATION "\${CMAKE_CURRENT_SOURCE_DIR}/work")
    endif()
    add_lab_app(project_${projectNumber}_work work)
endif()
`;
  const testAssets =
    project.sourceSeries === "flock-workbench" && projectNumber >= 68
      ? "    target_compile_definitions(project_" +
        projectNumber +
        '_tests PRIVATE COURSE_TEST_ASSETS="${CMAKE_CURRENT_SOURCE_DIR}/assets")\n'
      : "";
  // Opt-in for rebuilt shader tools: concurrent targets must not overwrite
  // each other's fallback files in a shared runtime/shaders directory.
  const shaderRuntime = project.shaderRuntimePerTarget ? "shaders/${name}" : "shaders";
  const shaderSetup = hasSnapshotShaders
    ? `
    # Shader thay đổi theo checkpoint được chạy trực tiếp từ source để hỗ trợ hot reload.
    target_compile_definitions(\${name} PRIVATE
        COURSE_SHADER_DIRECTORY="\${CMAKE_CURRENT_SOURCE_DIR}/\${source_directory}/shaders"
        COURSE_SHADER_FALLBACK_SUBDIRECTORY="${shaderRuntime}"
    )
    add_custom_command(TARGET \${name} POST_BUILD
        COMMAND \${CMAKE_COMMAND} -E copy_directory
            "\${CMAKE_CURRENT_SOURCE_DIR}/\${source_directory}/shaders"
            "$<TARGET_FILE_DIR:\${name}>/${shaderRuntime}"
    )
`
    : "";
  return `# Generated from scripts/course-cmake.mjs. Do not edit this file directly.
cmake_minimum_required(VERSION 3.24)
project(project_${projectNumber} LANGUAGES CXX)

set(CMAKE_CXX_STANDARD 20)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
set(CMAKE_CXX_EXTENSIONS OFF)

option(COURSE_USE_INSTALLED_SDL3 "Use an exact SDL 3.4.8 package supplied by CI" OFF)
if(COURSE_USE_INSTALLED_SDL3)
    find_package(SDL3 3.4.8 EXACT CONFIG REQUIRED)
else()
    include(FetchContent)
    # Khóa SDL ở đúng release và checksum để mọi máy dùng cùng source.
    set(SDL_TESTS OFF CACHE BOOL "" FORCE)
    set(SDL_EXAMPLES OFF CACHE BOOL "" FORCE)
    set(SDL_INSTALL OFF CACHE BOOL "" FORCE)
    FetchContent_Declare(SDL3
        URL https://github.com/libsdl-org/SDL/releases/download/release-3.4.8/SDL3-3.4.8.tar.gz
        URL_HASH SHA256=e9fff7467fb60f037e6708da18b25560649e4c63edc2a69bb871b960d9cbfbba
    )
    FetchContent_MakeAvailable(SDL3)
endif()

option(BUILD_CHECKPOINTS "Build starter and lesson checkpoints" OFF)
set(PROJECT_CHECKPOINT_COUNT ${project.checkpointCount})

# Dùng cùng mức warning cho final, starter, checkpoint và tests.
function(enable_course_warnings target)
    if(MSVC)
        target_compile_options(\${target} PRIVATE /W4 /permissive-)
    else()
        target_compile_options(\${target} PRIVATE -Wall -Wextra -Wpedantic)
    endif()
endfunction()

# Chuẩn bị runtime files đúng một lần mỗi build/configuration. Nhiều executable
# cùng POST_BUILD copy vào một thư mục sẽ tranh chấp file khi build song song.
get_property(is_multi_config GLOBAL PROPERTY GENERATOR_IS_MULTI_CONFIG)
set(runtime_directory "\${CMAKE_CURRENT_BINARY_DIR}")
if(is_multi_config)
    string(APPEND runtime_directory "/$<CONFIG>")
endif()
add_custom_target(project_${projectNumber}_runtime_files
    COMMAND \${CMAKE_COMMAND} -E make_directory "\${runtime_directory}"
    VERBATIM
)
if(WIN32 AND TARGET SDL3::SDL3-shared)
    add_custom_command(TARGET project_${projectNumber}_runtime_files POST_BUILD
        COMMAND \${CMAKE_COMMAND} -E copy_if_different
            "$<TARGET_FILE:SDL3::SDL3-shared>"
            "\${runtime_directory}"
        VERBATIM
    )
endif()
if(EXISTS "\${CMAKE_CURRENT_SOURCE_DIR}/assets")
    add_custom_command(TARGET project_${projectNumber}_runtime_files POST_BUILD
        COMMAND \${CMAKE_COMMAND} -E copy_directory
            "\${CMAKE_CURRENT_SOURCE_DIR}/assets"
            "\${runtime_directory}/assets"
        VERBATIM
    )
endif()

# Mỗi target biên dịch toàn bộ translation unit trong src của snapshot tương ứng.
function(add_lab_app name source_directory)
    file(GLOB_RECURSE lab_sources CONFIGURE_DEPENDS
        "\${CMAKE_CURRENT_SOURCE_DIR}/\${source_directory}/src/*.cc"
        "\${CMAKE_CURRENT_SOURCE_DIR}/\${source_directory}/src/*.cpp"
        "\${CMAKE_CURRENT_SOURCE_DIR}/\${source_directory}/src/*.cxx"
    )
    if(NOT lab_sources)
        message(FATAL_ERROR "\${source_directory}/src must contain at least one C++ source file")
    endif()
    add_executable(\${name} \${lab_sources})
    target_include_directories(\${name} PRIVATE \${source_directory}/include)
    target_link_libraries(\${name} PRIVATE SDL3::SDL3)
    add_dependencies(\${name} project_${projectNumber}_runtime_files)
${shaderSetup}    enable_course_warnings(\${name})
endfunction()

add_lab_app(project_${projectNumber}_final final)
${workbook}if(BUILD_CHECKPOINTS OR COURSE_TEST_STARTER)
    add_lab_app(project_${projectNumber}_starter starter)
endif()
if(BUILD_CHECKPOINTS)
    foreach(step RANGE 1 \${PROJECT_CHECKPOINT_COUNT})
        if(step LESS 10)
            set(step_directory "0\${step}")
        else()
            set(step_directory "\${step}")
        endif()
        add_lab_app(project_${projectNumber}_checkpoint_\${step} checkpoints/\${step_directory})
    endforeach()
endif()

# Một cấu hình chỉ kiểm một cây mã. Không tìm tiếp trong final/ nếu bài làm còn thiếu hàm.
include(CTest)
if(BUILD_TESTING)
    file(GLOB_RECURSE test_sources CONFIGURE_DEPENDS "\${CMAKE_CURRENT_SOURCE_DIR}/tests/*.cpp")
    add_executable(project_${projectNumber}_tests \${test_sources})
    if(${workOption})
        target_include_directories(project_${projectNumber}_tests PRIVATE work/include)
        set(test_tree work)
    elseif(COURSE_TEST_STARTER)
        target_include_directories(project_${projectNumber}_tests PRIVATE starter/include)
        set(test_tree starter)
    else()
        target_include_directories(project_${projectNumber}_tests PRIVATE final/include)
        set(test_tree final)
    endif()
${testAssets}    enable_course_warnings(project_${projectNumber}_tests)
    if(test_tree STREQUAL "final")
        set(test_label reference)
    else()
        set(test_label learner)
        # CTest không được chạy nhầm binary đã build cho cây khác. Ở các bài đầu
        # chỉ build ứng dụng; tests toàn project có thể cần API chưa học tới.
        set_target_properties(project_${projectNumber}_tests PROPERTIES
            OUTPUT_NAME "project_${projectNumber}_\${test_tree}_tests")
        add_custom_target(project_${projectNumber}_check_work
            COMMAND "\${CMAKE_CTEST_COMMAND}" -C "$<CONFIG>" -L "^learner$" --no-tests=error --output-on-failure --timeout 45
            WORKING_DIRECTORY "\${CMAKE_CURRENT_BINARY_DIR}"
            DEPENDS project_${projectNumber}_tests
            VERBATIM)
    endif()
    message(STATUS "CTest: \${test_label} (\${test_tree}/include)")
    if(test_tree STREQUAL "final")
        message(STATUS "Reference only. For your own code configure with -DCOURSE_TEST_STARTER=ON (starter/) or -D${workOption}=ON (work/).")
    else()
        message(STATUS "Build target project_${projectNumber}_check_work to rebuild and test your own code.")
    endif()
    set(test_name project_${projectNumber}_\${test_tree}_validation)
    add_test(NAME \${test_name} COMMAND project_${projectNumber}_tests)
    set_tests_properties(\${test_name} PROPERTIES LABELS \${test_label})
endif()
`;
}
